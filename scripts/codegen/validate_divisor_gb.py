#!/usr/bin/env python3
"""Independent set-polynomial arithmetic and physical-column GB validator.

No constructor or logical-builder imports. GPL-3.0-or-later.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
from validate_css import basis,contains,dot,equal_space,read_code,validate


def mod(a,b):
    a=set(a);b=set(b)
    if not b:raise ValueError('zero divisor')
    while a and max(a)>=max(b):
        shift=max(a)-max(b);a.symmetric_difference_update(x+shift for x in b)
    return a


def common(a,b):
    a,b=set(a),set(b)
    while b:a,b=b,mod(a,b)
    return a


def multiply(a,b,l):
    counts=Counter((x+y)%l for x in a for y in b)
    return {x for x,count in counts.items() if count%2}


def facts(c):
    l=c['l'];p=[]
    for name,lift in (('a','u'),('b','v')):
        values=[]
        if name in c:values.append(set(c[name]))
        if lift in c:values.append(multiply(c['g'],c[lift],l))
        if not values or any(x!=values[0] for x in values):raise ValueError('source polynomial/lift disagreement')
        p.append(values[0])
    for key in ('g','a','b','u','v'):
        if key in c and (len(c[key])!=len(set(c[key])) or any(type(x)!=int or not 0<=x<l for x in c[key])):
            raise ValueError('invalid source support')
    g=common(common(*p),{0,l})
    if g!=set(c['g']) or 2*max(g)!=c['k'] or 2*l!=c['n']:raise ValueError('source gcd/dimension mismatch')
    return p,g


def reconstruct(c):
    (a,b),_=facts(c);l=c['l'];out=[]
    # Enumerate physical columns and infer incident roots, independently of
    # the constructor's translated-row procedure and bit polynomial arithmetic.
    for half in (0,1):
        rows=[0]*l
        for q in range(2*l):
            block,h=divmod(q,l);support=(b,a)[block] if half else (a,b)[block]
            for r in range(l):
                if ((h-r) if half else (r-h))%l in support:rows[r]|=1<<q
        out.append(rows)
    return out


def permute(row,order):return sum(((row>>i)&1)<<j for i,j in enumerate(order))


def connected(n,rows):
    parent=list(range(n))
    def root(x):
        while parent[x]!=x:parent[x]=parent[parent[x]];x=parent[x]
        return x
    for row in rows:
        support=[q for q in range(n) if (row>>q)&1]
        for q in support[1:]:parent[root(q)]=root(support[0])
    return len({root(q) for q in range(n)})==1


def certify(c,n,matrices):
    hx,hz,gx,gz=matrices;expected=reconstruct(c)
    if [hx,hz]!=expected:raise ValueError('matrix differs from independent physical columns')
    result=validate(n,matrices);(a,b),g=facts(c);l=c['l']
    if n!=c['n'] or result['k']!=c['k'] or result['rank_Hx']!=l-max(g) or result['rank_Hz']!=l-max(g):
        raise ValueError('polynomial versus binary rank mismatch')
    w=len(a)+len(b)
    if w!=c['expected_weight'] or any(bin(r).count('1')!=w for r in hx+hz):raise ValueError('check weight mismatch')
    if len(set(hx))!=l or len(set(hz))!=l:raise ValueError('duplicate check row')
    if not connected(n,hx) or not connected(n,hz):raise ValueError('disconnected Tanner graph')
    for rows,weights in ((hx,(len(a),len(b))),(hz,(len(b),len(a)))):
        if any(sum((r>>q)&1 for r in rows)!=weights[q//l] for q in range(n)):raise ValueError('column degree mismatch')
    # Every cyclic shift is generated by shift1. Reflection plus block swap
    # exchanges the two spaces, independently checked as physical permutations.
    shift=[(q//l)*l+(q%l+1)%l for q in range(n)]
    dual=[(1-q//l)*l+(-q%l)%l for q in range(n)]
    if not all(equal_space(rows,[permute(r,shift) for r in rows]) for rows in (hx,hz)):
        raise ValueError('cyclic translation not an automorphism')
    if not equal_space(hz,[permute(r,dual) for r in hx]) or not equal_space(hx,[permute(r,dual) for r in hz]):
        raise ValueError('reflection/block-swap dual map failed')
    involution=multiply(a,{(-x)%l for x in b},l)^multiply(b,{(-x)%l for x in a},l)
    if involution:raise ValueError('published stronger involution identity failed')
    witnesses=[]
    for half,parity,stab,logical,detector in (('Z',hx,hz,gx,gz),('X',hz,hx,gz,gx)):
        word=min(logical,key=lambda x:(bin(x).count('1'),x));support=[q for q in range(n) if (word>>q)&1]
        if any(dot(word,r) for r in parity) or contains(basis(stab),word) or not any(dot(word,r) for r in detector):
            raise ValueError('basis upper witness invalid')
        if len(support)<c['d']:raise ValueError('SCIENTIFIC MISMATCH: word below published exact distance')
        witnesses.append(dict(half=half,support=support,weight=len(support)))
    result.update(stem=f'GB_{n}_{c["k"]}_unknown',polynomial_a=sorted(a),polynomial_b=sorted(b),common_gcd=sorted(g),
                  row_weight=w,column_weights_Hx=[len(a),len(b)],connected_both_halves=True,
                  cyclic_translation=True,reflection_block_swap_duality=True,stronger_source_involution=True,
                  witnesses=witnesses,verified_basis_ub=min(x['weight'] for x in witnesses))
    return result


def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--dir',type=Path,default=Path('data/matrices/untiered'))
    ap.add_argument('--cases',type=Path,default=Path(__file__).with_name('divisor_gb_cases.json'))
    ap.add_argument('--output',type=Path,required=True);args=ap.parse_args();results=[]
    for c in json.loads(args.cases.read_text()):
        n,m=read_code(args.dir,f'GB_{c["n"]}_{c["k"]}_unknown');results.append(certify(c,n,m))
    text=json.dumps(results,indent=2)+'\n';args.output.write_text(text);print(text,end='')


if __name__=='__main__':main()
