Require Import VST.floyd.proofauto.
Require Import CCV.ccv_primitives CCV.CCWord.
#[export] Instance CompSpecs : compspecs. make_compspecs prog. Defined.
Definition Vprog : varspecs. mk_varspecs prog. Defined.
Definition bv (b:bool) : val := Vint (Int.repr (if b then 1 else 0)).
Definition bit_xor_spec : ident * funspec :=
 DECLARE _ccv_bit_xor
 WITH a:bool,b:bool
 PRE [tuint,tuint] PROP() PARAMS(bv a;bv b) SEP()
 POST [tuint] PROP() RETURN(bv (xorb a b)) SEP().
Definition ceil_div_spec : ident * funspec :=
 DECLARE _ccv_ceil_div
 WITH a:int,b:int
 PRE [tuint,tuint]
 PROP(Int.unsigned b<>0) PARAMS(Vint a;Vint b) SEP()
 POST [tuint] PROP()
 RETURN(Vint (Int.repr (ceil_Z (Int.unsigned a) (Int.unsigned b)))) SEP().
Definition Gprog : funspecs := ltac:(with_library prog [bit_xor_spec;ceil_div_spec]).
Lemma body_bit_xor : semax_body Vprog Gprog f_ccv_bit_xor bit_xor_spec.
Proof.
 start_function. unfold bv in *.
 destruct a,b; forward; entailer!.
Qed.
Lemma body_ceil_div : semax_body Vprog Gprog f_ccv_ceil_div ceil_div_spec.
Proof.
 start_function. forward.
 entailer!. f_equal.
 rewrite <- (machine_ceil_repr a b H).
 unfold machine_ceil;fold Int.zero.
 destruct (Int.eq (Int.modu a b) Int.zero);reflexivity.
Qed.
Print Assumptions body_bit_xor.
Print Assumptions body_ceil_div.
