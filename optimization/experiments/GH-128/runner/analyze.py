#!/usr/bin/env python3
"""GH-128 analysis. usage: analyze.py T04_RESULTS.jsonl MAC_RESULTS.jsonl TIER5_RESULTS.json SERVER.md > summary.md"""
import json, math, re, statistics as st, sys
from collections import defaultdict

t04 = [json.loads(l) for l in open(sys.argv[1])]
mac = [json.loads(l) for l in open(sys.argv[2])]
t5 = json.load(open(sys.argv[3]))['results'] if len(sys.argv) > 3 and sys.argv[3] != '-' else []
srv = open(sys.argv[4]).read() if len(sys.argv) > 4 else ''
P = print
gm = lambda xs: math.exp(sum(math.log(x) for x in xs) / len(xs)) if xs else float('nan')


def index(rs):
    d = {}
    for r in rs: d[(r['stem'], r['mode'], r['seed'], r['arm'])] = r
    return d


def identity_section(rs, host):
    d = index(rs)
    cells = sorted({(r['tier'], r['stem'], r['mode']) for r in rs})
    P(f'### {host}: per cell (default seed)\n')
    P('| Tier | Code | Mode | d | off s | on s | on/off | fingerprint on = off | off = main | p1skip lines (on) | checks |')
    P('|---:|---|---|---:|---:|---:|---:|---|---|---|---|')
    trig = []; bad = 0; nid = 0; nmain = 0; nmain_ok = 0
    for t, s, m in cells:
        off, on, mn = d.get((s, m, 0, 'off')), d.get((s, m, 0, 'on')), d.get((s, m, 0, 'main'))
        if not off or not on: continue
        same = off['fingerprint'] == on['fingerprint']
        nid += same
        msame = '-' if not mn else ('yes' if mn['fingerprint'] == off['fingerprint'] else 'NO')
        if mn: nmain += 1; nmain_ok += mn['fingerprint'] == off['fingerprint']
        sk = '; '.join(x.replace('c p1skip: ', '') for x in on['p1skip_lines']) or '-'
        if on['p1skip_lines']: trig.append((t, s, m))
        oks = all(x['ok'] for x in (off, on) + ((mn,) if mn else ()))
        ans = {x['result'] for x in (off, on) + ((mn,) if mn else ())}
        if not oks or len(ans) != 1: bad += 1
        P(f"| {t} | {s} | {m} | {on['result']} | {off['wall']:.2f} | {on['wall']:.2f} | {on['wall']/off['wall']:.3f} | "
          f"{'yes' if same else 'no (skip)'} | {msame} | {sk} | {'ok' if oks and len(ans)==1 else 'FAIL ' + str([x['issues'] for x in (off,on)])} |")
    P(f'\n{host}: {len(cells)} cells; fingerprint on = off in {nid}; off = main in {nmain_ok}/{nmain}; '
      f'skip triggered in {len(trig)}: {", ".join(f"{s} {m}" for _, s, m in trig) or "none"}; check failures {bad}.\n')
    return trig


P('# GH-128 S1 summary (generated by runner/analyze.py)\n')
P('## Server tier0-4 (yfclab2, cores 52-59, -v -dualshare-stats)\n')
trig = identity_section(t04, 'server')

# seeds 1-4 identity + seed-median ratios tier1-2 (all seeds), default seed tiers 3-4
d = index(t04)
P('### server: seed identity and on/off ratios\n')
P('| Tier | Code | Mode | seeds run | fingerprint on = off (seeds) | off median s (range) | on median s (range) | ratio on/off |')
P('|---:|---|---|---:|---|---|---|---:|')
byt = defaultdict(lambda: defaultdict(list)); cellr = []
for t, s, m in sorted({(r['tier'], r['stem'], r['mode']) for r in t04}):
    seeds = sorted({r['seed'] for r in t04 if r['stem'] == s and r['mode'] == m and r['arm'] == 'on'})
    offs = [d[(s, m, x, 'off')]['wall'] for x in seeds if (s, m, x, 'off') in d]
    ons = [d[(s, m, x, 'on')]['wall'] for x in seeds if (s, m, x, 'on') in d]
    ids = sum(d[(s, m, x, 'off')]['fingerprint'] == d[(s, m, x, 'on')]['fingerprint'] for x in seeds
              if (s, m, x, 'off') in d and (s, m, x, 'on') in d)
    if not offs or not ons: continue
    r = st.median(ons) / st.median(offs)
    byt[t][m].append(r); cellr.append((r, t, s, m))
    P(f'| {t} | {s} | {m} | {len(seeds)} | {ids}/{len(seeds)} | {st.median(offs):.2f} ({min(offs):.2f}-{max(offs):.2f}) | '
      f'{st.median(ons):.2f} ({min(ons):.2f}-{max(ons):.2f}) | {r:.3f} |')
P('\n| Tier | no-card geomean on/off | card-mto geomean on/off | max cell |')
P('|---:|---:|---:|---|')
for t in sorted(byt):
    mx = max((c for c in cellr if c[1] == t), key=lambda c: c[0])
    P(f"| {t} | {gm(byt[t]['no-card']):.3f} | {gm(byt[t]['card-mto']):.3f} | {mx[0]:.3f} ({mx[2]} {mx[3]}) |")
P('\nCells with ratio > 1: ' + (', '.join(f'{s} {m} {r:.3f}' for r, t, s, m in sorted(cellr, reverse=True) if r > 1) or 'none')
  + '; cells > 1.25: ' + (', '.join(f'{s} {m}' for r, t, s, m in cellr if r > 1.25) or 'none') + '.\n')

P('## Mac tier0-2 quick check (serial, caffeinate, 2 GB watchdog; main = frozen abd1770)\n')
identity_section(mac, 'Mac')

if t5:
    P('## Tier 5 (6 h, default seed): -p1skip=on vs recorded main 398054e (SERVER.md)\n')
    mainrows = {}
    for l in srv.splitlines():
        m = re.match(r'\| (\w+) \| (no-card|card-mto) \| (\d+) \| (\w+) \| (\d+|-) \| (\d+|-) \| (.*) \|$', l)
        if m: mainrows[(m.group(1), m.group(2))] = m.groups()
    P('| Code | Mode | main | p1skip=on | lb vs main | ub vs main | on lb events | ub-to-answer gap (s) | checks |')
    P('|---|---|---|---|---|---|---|---:|---|')
    solved_m = solved_o = 0; ratios = []
    for r in sorted(t5, key=lambda r: (r['stem'], r['mode'])):
        k = (r['stem'], r['mode']); mr = mainrows.get(k)
        lbs = r['lb_events']; ubs = r['ub_events']
        flb = max([x for _, x in lbs], default=None); fub = min([x for _, x in ubs], default=None)
        if r['result']:
            on = f"d={r['result'][1]} @ {r['result'][0]:.0f} s"; solved_o += 1
            first = min((t for t, x in ubs if x == r['result'][1]), default=None)
            gap = f"{r['result'][0] - first:.1f}" if first is not None else '-'
        else:
            on = f"T, {flb}/{fub if fub is not None else '-'}"; gap = '-'
        if mr:
            if mr[3] == 'solved': ms = f'd={mr[4]} @ {mr[2]} s'; solved_m += 1
            else: ms = f'T, {mr[4]}/{mr[5]}'
            mlb = int(mr[4]); mub = None if mr[5] == '-' else int(mr[5])
            olb = r['result'][1] if r['result'] else flb
            oub = r['result'][1] if r['result'] else fub
            c_lb = '=' if olb == mlb else ('>' if olb > mlb else '<')
            c_ub = '=' if oub == mub else ('-' if oub is None and mub is None else (
                'new' if mub is None else ('lost' if oub is None else ('<' if oub < mub else '>'))))
            if r['result'] and mr[3] == 'solved': ratios.append((r['result'][0] / float(mr[2]), k))
        else:
            ms = 'n/a'; c_lb = c_ub = '?'
        ev = ', '.join(f'{x}@{t:.0f}' for t, x in lbs if x >= 9)
        P(f"| {r['stem']} | {r['mode']} | {ms} | {on} | {c_lb} | {c_ub} | {ev} | {gap} | {'ok' if r['science_ok'] else 'FAIL ' + str(r['issues'])} |")
    P(f'\nSolved cells: main {solved_m}, p1skip=on {solved_o}. Time ratios on/main where both solved: '
      + ', '.join(f'{k[0]} {k[1]} {x:.3f}' for x, k in ratios) + (f'; geomean {gm([x for x, _ in ratios]):.3f}' if ratios else '') + '.\n')
